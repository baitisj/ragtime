#!/usr/bin/env python3
"""Writes core/src/globus/LakeOutlines.h, the big lakes Globus fills in the
sea's colour over the land.

Natural Earth's 1:110m countries fill the lakes in as land, so without
these the Great Lakes are dry and Michigan runs into Wisconsin. The source
is ne_110m_lakes.geojson beside this script, Natural Earth's 1:110m lakes
(public domain, https://www.naturalearthdata.com/), from
https://github.com/nvkelso/natural-earth-vector/tree/master/geojson. Only
the standard library is needed:

    python3 tools/globe/gen_lake_outlines.py --write

Each lake's outer ring is kept (none of these has an island at 1:110m),
turned clockwise (east right, north up) like the land's outlines, so the
same code fills both. Long edges are split as for the coastlines, and the
points go in hundredths of a degree.
"""

import argparse
import json
import os
import sys

from gen_land_outlines import densified, signed_area, SCALE

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "ne_110m_lakes.geojson")
OUT = os.path.join(HERE, "..", "..", "core", "src", "globus", "LakeOutlines.h")


def read_lakes(path):
    """Each lake's name and outer rings, as lists of (lon, lat), the closing point dropped."""
    with open(path) as f:
        collection = json.load(f)
    lakes = []
    for feature in collection["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in polygons:
            ring = [tuple(p[:2]) for p in polygon[0]]
            if len(ring) > 1 and ring[0] == ring[-1]:
                ring = ring[:-1]
            if len(ring) >= 3:
                lakes.append((feature["properties"]["name"], ring))
    return lakes


def header(lakes):
    starts = []
    values = []
    for _, ring in lakes:
        starts.append(len(values) // 2)
        for lon, lat in ring:
            values.append(int(round(lon * SCALE)))
            values.append(int(round(lat * SCALE)))
    starts.append(len(values) // 2)
    names = ", ".join(name for name, _ in lakes)

    def wrap(numbers, per_line):
        rows = []
        for i in range(0, len(numbers), per_line):
            rows.append("    " + ", ".join(str(v) for v in numbers[i:i + per_line]) + ",")
        return "\n".join(rows)

    def wrapped_names(text, width=72):
        rows, row = [], "//"
        for word in text.split(" "):
            if len(row) + 1 + len(word) > width:
                rows.append(row)
                row = "//"
            row += " " + word
        rows.append(row)
        return "\n".join(rows)

    return f"""//=========================================================================
// Name:            LakeOutlines.h
// Purpose:         The big lakes on Globus. Generated by
//                  tools/globe/gen_lake_outlines.py from Natural Earth's
//                  1:110m lakes (public domain); do not edit by hand.
//
// {len(lakes)} lakes. Ring r is POINTS[RING_START[r]] up to RING_START[r + 1], each
// point a longitude then a latitude in hundredths of a degree, clockwise
// (east right, north up) like the land; the last point joins back to the
// first. In order:
{wrapped_names(names)}
//=========================================================================

#ifndef RAGTIME_GLOBUS_LAKE_OUTLINES_H
#define RAGTIME_GLOBUS_LAKE_OUTLINES_H

#include <cstdint>

namespace LakeOutlines
{{

constexpr int RING_COUNT = {len(lakes)};
constexpr int POINT_COUNT = {len(values) // 2};
constexpr double UNITS_PER_DEGREE = {SCALE}.0;

constexpr uint32_t RING_START[RING_COUNT + 1] = {{
{wrap(starts, 12)}
}};

constexpr int16_t POINTS[POINT_COUNT * 2] = {{
{wrap(values, 16)}
}};

}} // namespace LakeOutlines

#endif // RAGTIME_GLOBUS_LAKE_OUTLINES_H
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", nargs="?", default=SOURCE)
    parser.add_argument("--write", action="store_true", help="write LakeOutlines.h rather than report")
    args = parser.parse_args()

    lakes = []
    for name, ring in read_lakes(args.source):
        # Clockwise, as the land is: a negative signed area, east right and
        # north up.
        if signed_area(ring) > 0:
            ring = ring[::-1]
        lakes.append((name, densified(ring)))
    text = header(lakes)
    points = sum(len(ring) for _, ring in lakes)
    print(f"{len(lakes)} lakes, {points} points, {len(text)} bytes of header", file=sys.stderr)
    if args.write:
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.normpath(OUT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
