#!/usr/bin/env python3
"""Builds core/include/ragtime/text/HamTextTable.h: the phrases and the code
lengths HamText codes Ragtime's text with (text table 0, docs/PROTOCOL.md).

Ported from Glissando's prototype/ham_table/gen_table.py, which built the
same table for Glissando; Ragtime's table 0 is that table, symbol for
symbol.

Symbols: printable ASCII 0x20-0x7E, then the phrases of phrases.txt (each
coded as one symbol), then ESC (a raw byte follows) and EMPTY (the rest is
padding). Character counts come from chat_corpus.txt, 94 typical chat
lines, blended 70/30 with prose.txt, the prose of Glissando's docs as they
stood at its commit 493f13a (October 2026), so ordinary English is not
punished for missing from the small sample. EMPTY is forced to be the
rarest symbol, so the complemented canonical code gives it the all-zero
codeword.

Text is split into symbols as the encoder splits it: at each character the
longest phrase that starts there, else the character itself.

    python3 gen_table.py            prints the table
    python3 gen_table.py --write    rewrites HamTextTable.h
    python3 gen_table.py --check    fails if HamTextTable.h is not what this makes
"""
import collections
import heapq
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'core', 'include', 'ragtime', 'text', 'HamTextTable.h')

msgs = [l.rstrip('\n') for l in open(os.path.join(HERE, 'chat_corpus.txt')) if l.strip()]
# Wrapped at spaces for the diff's sake: the lines join back with a space.
prose = ' '.join(l.rstrip('\n') for l in open(os.path.join(HERE, 'prose.txt')))
PHRASES = [json.loads(l) for l in open(os.path.join(HERE, 'phrases.txt')) if l.strip() and not l.startswith('#')]
for p in PHRASES:
    assert len(p) > 1 and all(32 <= ord(c) < 127 for c in p), p
assert len(set(PHRASES)) == len(PHRASES)

NSYM = 95 + len(PHRASES) + 2
ESC = NSYM - 2
EMPTY = NSYM - 1
PHRASE_FLOOR = 0.7 / 1000
BY_LENGTH = sorted(range(len(PHRASES)), key=lambda i: -len(PHRASES[i]))


def symbols(t):
    i = 0
    while i < len(t):
        for k in BY_LENGTH:
            if t.startswith(PHRASES[k], i):
                yield 95 + k
                i += len(PHRASES[k])
                break
        else:
            yield ord(t[i]) - 32
            i += 1


def counts(texts, weight):
    c = collections.Counter()
    n = 0
    for t in texts:
        for s in symbols(t):
            c[s] += 1
            n += 1
    return {k: v * weight / n for k, v in c.items()}


def lengths(maxlen=15):
    f = [1e-4] * NSYM
    for src in (counts(msgs, 0.7), counts([prose], 0.3)):
        for k, v in src.items():
            f[k] += v
    # A listed phrase the small corpus rarely or never uses is still
    # expected on the air (fb, qsy, agn): count it as at least about once
    # per 30 chat lines, so its code stays shorter than spelling it out.
    for k in range(len(PHRASES)):
        f[95 + k] = max(f[95 + k], PHRASE_FLOOR)
    f[ESC] = 2e-4
    f[EMPTY] = min(f) / 2
    while True:
        h = [(f[i], i, (i,)) for i in range(NSYM)]
        heapq.heapify(h)
        L = [0] * NSYM
        k = NSYM
        while len(h) > 1:
            a = heapq.heappop(h)
            b = heapq.heappop(h)
            for s in a[2] + b[2]:
                L[s] += 1
            heapq.heappush(h, (a[0] + b[0], k, a[2] + b[2]))
            k += 1
        if max(L) <= maxlen:
            break
        f = [x ** 0.9 for x in f]
        f[EMPTY] = min(f[:EMPTY]) / 2
    assert abs(sum(2 ** -l for l in L) - 1) < 1e-12
    assert L[EMPTY] == max(L)
    return L


def spelled(L, p):
    return sum(L[ord(c) - 32] for c in p)


def header(L):
    rows = []
    for i in range(0, 95, 16):
        rows.append('    ' + ', '.join(f'{x:2d}' for x in L[i:min(i + 16, 95)]) + ',' + ' // ' +
                    ''.join(chr(32 + j) for j in range(i, min(i + 16, 95))))
    for k, p in enumerate(PHRASES):
        rows.append(f'    {L[95 + k]:2d}, // {json.dumps(p)} (spelled out: {spelled(L, p)} bits)')
    rows.append(f'    {L[ESC]:2d}, // ESC')
    rows.append(f'    {L[EMPTY]:2d}, // EMPTY')
    phrases = ''.join(f'    {json.dumps(p)},\n' for p in PHRASES)
    return f"""// The ham chat text table, Ragtime's text table 0: phrases coded as one
// symbol, and the Huffman code length of every symbol.
//
// Generated by tools/ham_table/gen_table.py from phrases.txt,
// chat_corpus.txt and prose.txt. Do not edit by hand: edit phrases.txt and
// run
//   python3 tools/ham_table/gen_table.py --write
// Both ends need the same table, so any change here is a new table number
// (docs/PROTOCOL.md, "Text coding").
#ifndef RAGTIME_TEXT_HAM_TEXT_TABLE_H
#define RAGTIME_TEXT_HAM_TEXT_TABLE_H

#include <cstdint>

namespace ragtime
{{
namespace text
{{

// Matched exactly and case sensitively, longest first.
constexpr const char* PHRASES[] = {{
{phrases}}};
constexpr int PHRASE_COUNT = {len(PHRASES)};

// Symbols: printable ASCII 0x20-0x7E, PHRASES in order, ESC, EMPTY.
constexpr int SYMBOL_COUNT = 95 + PHRASE_COUNT + 2;
constexpr uint8_t SYMBOL_BITS[SYMBOL_COUNT] = {{
""" + '\n'.join(rows) + """
};

} // namespace text
} // namespace ragtime

#endif
"""


if __name__ == '__main__':
    L = lengths()
    for k, p in enumerate(PHRASES):
        assert L[95 + k] < spelled(L, p), f'{p!r} costs {L[95 + k]} bits, no less than spelled out'
    text = header(L)
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('HamTextTable.h is up to date' if same else 'HamTextTable.h differs: run gen_table.py --write')
        sys.exit(0 if same else 1)
    print('max', max(L), 'EMPTY', L[EMPTY], 'ESC', L[ESC])
    print(''.join(f"{chr(32 + i)}:{L[i]} " for i in range(95) if L[i] <= 6))
    for k, p in enumerate(PHRASES):
        print(f'{p!r}: {L[95 + k]} bits (spelled out {spelled(L, p)})')
    if '--write' in sys.argv:
        with open(OUT, 'w') as f:
            f.write(text)
        print('wrote', OUT)
