// HamText: Huffman codes text with a fixed table drawn from ham chat, so
// common characters cost fewer bits. This is Ragtime's text table 0
// (docs/PROTOCOL.md, "Text coding").
//
// Ported from Glissando's HamText (written there for Glissando, Jeff,
// 2026-10-04) and relicensed MIT by Jeff. Measured on 94 typical chat
// lines, the table spends about five bits a character instead of eight.
//
// The table is fixed, so every record decodes on its own. Glissando kept
// codes inside 9-byte blocks, its frame segments; a Ragtime record arrives
// whole or not at all, so here the whole record's text is one block.
//
// A few whole phrases, such as " the" and "CQ CQ", are symbols of their
// own (HamTextTable.h, generated by tools/ham_table/gen_table.py). The
// encoder codes the longest phrase that starts at each character, and
// phraseSpans() finds the same ones, so an entry box can show which parts
// of a message ride as one symbol.
//
// Bytes outside printable ASCII (accents, all of UTF-8 beyond ASCII) go as
// an escape code and the raw byte, so any byte string comes back exactly
// as it went in. The rarest code, all zero bits, means "the rest is
// empty": zero padding reads as it, so the text needs no length field and
// no end marker.
#ifndef RAGTIME_TEXT_HAM_TEXT_H
#define RAGTIME_TEXT_HAM_TEXT_H

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace ragtime
{
namespace text
{

// Writes count bits of value, most significant first, at bit position bit
// of bytes (bit 0 is the top bit of bytes[0]). The bits must be zero.
void putBits(uint8_t* bytes, size_t bit, uint64_t value, int count);

// Reads count (at most 64) bits at bit position bit.
uint64_t getBits(const uint8_t* bytes, size_t bit, int count);

namespace HamText
{

// How many bits a byte costs on its own, escape included.
int characterBits(unsigned char c);

// Where the encoder codes a phrase as one symbol: each phrase found
// scanning text from the start, longest match first, as encode() scans it.
struct PhraseSpan
{
    size_t start;
    size_t length;
};
std::vector<PhraseSpan> phraseSpans(const std::string& text);

// How many bits encode() spends on text, before padding to a byte.
size_t bits(const std::string& text);

// The text coded, zero padded to a whole byte.
std::vector<uint8_t> encode(const std::string& text);

// The text back from coded bytes. Decoding stops at the padding, at an
// EMPTY code, or at a code cut short by the end.
std::string decode(const uint8_t* bytes, size_t length);
inline std::string decode(const std::vector<uint8_t>& bytes)
{
    return decode(bytes.data(), bytes.size());
}

} // namespace HamText

} // namespace text
} // namespace ragtime

#endif
